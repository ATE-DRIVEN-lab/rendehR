# ---- Background jobs: run real pipeline work in a detached Rscript and watch
# its log from the app. The registry (.jobs) and JOBS_DIR live in the app
# environment; one poller in the server refreshes every running job. Jobs are
# honest: the log is the child process's full stdout/stderr, and the last line
# carries its exit status.

job_start <- function(name, lines, wd = NULL, config = NULL) {
  id <- paste0("j", format(Sys.time(), "%H%M%S"), "-", sample.int(9999, 1))
  dir.create(JOBS_DIR, showWarnings = FALSE, recursive = TRUE)
  script <- file.path(JOBS_DIR, paste0(id, ".R"))
  log <- file.path(JOBS_DIR, paste0(id, ".log"))
  pre <- c(
    "# Background job generated by the rendehR explorer.",
    sprintf('cat("job started ", format(Sys.time()), "\\n", sep = "")'),
    "res <- tryCatch({",
    "  suppressMessages(library(rendehR))",
    if (!is.null(config)) sprintf("  ehr_use_config(%s)", deparse(config)),
    if (!is.null(wd)) sprintf("  setwd(%s)", deparse(wd)),
    paste0("  ", lines),
    '  "OK"',
    "}, error = function(e) paste(\"ERROR:\", conditionMessage(e)))",
    'cat(sprintf("\\n[[JOB-EXIT:%s]]\\n", res))'
  )
  writeLines(pre, script)
  q <- function(x) shQuote(x)
  # the job sees the same libraries as this app (they may have been set in-session)
  cmd <- sprintf("R_LIBS=%s %s %s > %s 2>&1 & echo $!", q(paste(.libPaths(), collapse = .Platform$path.sep)),
                 q(file.path(R.home("bin"), "Rscript")), q(script), q(log))
  pid <- suppressWarnings(tryCatch(as.integer(system(cmd, intern = TRUE)), error = function(e) NA_integer_))
  if (length(pid) != 1L || is.na(pid)) pid <- NA_integer_
  .jobs$list[[id]] <- list(id = id, name = name, log = log, pid = pid,
                           started = format(Sys.time(), "%H:%M:%S"),
                           status = "running", detail = "")
  id
}

.job_alive <- function(pid) isTRUE(!is.na(pid) && tools::pskill(as.integer(pid), 0L))   # signal 0: exists?

# Refresh one running job from its log (exit marker) or from process liveness.
job_refresh <- function(id) {
  j <- .jobs$list[[id]]
  if (is.null(j) || !identical(j$status, "running")) return(invisible(NULL))
  txt <- tryCatch(readLines(j$log, warn = FALSE), error = function(e) character())
  m <- regmatches(txt, regexpr("\\[\\[JOB-EXIT:.*\\]\\]", txt))
  if (length(m)) {
    st <- sub("\\[\\[JOB-EXIT:(.*)\\]\\]", "\\1", m[length(m)])
    .jobs$list[[id]]$status <- if (identical(st, "OK")) "done" else "failed"
    .jobs$list[[id]]$detail <- if (identical(st, "OK")) "" else sub("^ERROR: ", "", st)
  } else if (!.job_alive(j$pid)) {
    .jobs$list[[id]]$status <- "failed"
    .jobs$list[[id]]$detail <- if (length(txt)) "process exited without an exit marker; see log"
                               else "process exited without output"
  }
  invisible(NULL)
}

job_cancel <- function(id) {
  j <- .jobs$list[[id]]
  if (!is.null(j) && identical(j$status, "running") && !is.na(j$pid))
    tryCatch(tools::pskill(j$pid), error = function(e) NULL)
  if (!is.null(j)) { .jobs$list[[id]]$status <- "cancelled"; .jobs$list[[id]]$detail <- "" }
  invisible(NULL)
}

# One poller per app session; call from the top-level server.
jobs_poller <- function(input, output, session) {
  observe({
    invalidateLater(2000, session)
    for (id in names(.jobs$list)) job_refresh(id)
  })
}

jobs_status_chip <- function(status, detail = "") {
  cls <- switch(status, running = "text-bg-secondary", done = "text-bg-success",
                failed = "text-bg-danger", cancelled = "text-bg-warning", "text-bg-light")
  lab <- switch(status, running = "running", done = "done", failed = "failed",
                cancelled = "cancelled", status)
  tags$span(class = sprintf("badge rounded-pill %s", cls), lab)
}

# Reusable component: a compact job list + log tail. Used on the Setup and
# Cohorts pages and, with more room, on the Package page.
jobs_ui <- function(id) {
  ns <- NS(id)
  tagList(
    uiOutput(ns("table")),
    conditionalPanel("output.has_jobs", ns = ns,
      layout_columns(col_widths = c(6, 6),
        selectInput(ns("job"), "Log of", choices = character()),
        tags$div(class = "rh-button-row justify-content-end mt-4",
                 actionButton(ns("cancel"), "Cancel task", icon = icon("ban"), class = "btn-outline-danger btn-sm"),
                 actionButton(ns("clear"), "Clear finished", class = "btn-sm"))),
      verbatimTextOutput(ns("log"))))
}
jobs_server <- function(id) moduleServer(id, function(input, output, session) {
  prev_ids <- reactiveVal(character())
  output$table <- renderUI({
    invalidateLater(2000, session)
    ids <- rev(names(.jobs$list) %||% character())
    if (!length(ids)) return(tags$p(class = "small text-muted mb-0", "No background tasks yet. Pipeline steps, imports and exports appear here with their logs."))
    rows <- lapply(ids, function(i) {
      j <- .jobs$list[[i]]
      tags$tr(tags$td(j$name), tags$td(j$started), tags$td(jobs_status_chip(j$status)), tags$td(class = "text-danger", j$detail))
    })
    tags$table(class = "table table-sm align-middle small mb-2",
      tags$thead(tags$tr(tags$th("Task"), tags$th("Started"), tags$th("Status"), tags$th(""))),
      tags$tbody(rows))
  })
  observe({
    invalidateLater(2000, session)
    ids <- rev(names(.jobs$list) %||% character())
    if (identical(ids, prev_ids())) return()
    prev_ids(ids)
    updateSelectInput(session, "job", choices = stats::setNames(ids, vapply(ids, function(i) .jobs$list[[i]]$name, character(1))),
                      selected = if (length(ids)) ids[1] else character())
  })
  output$log <- renderText({
    invalidateLater(2000, session)
    req(input$job)
    j <- .jobs$list[[input$job]]
    req(j)
    txt <- tryCatch(readLines(j$log, warn = FALSE), error = function(e) character())
    paste(utils::tail(txt, 120), collapse = "\n")
  })
  output$has_jobs <- reactive({ invalidateLater(2000, session); length(.jobs$list) > 0 })
  outputOptions(output, "has_jobs", suspendWhenHidden = FALSE)
  observeEvent(input$cancel, { req(input$job); job_cancel(input$job) })
  observeEvent(input$clear, {
    done <- names(Filter(function(j) !identical(j$status, "running"), .jobs$list))
    for (id in done) .jobs$list[[id]] <- NULL
  })
})
